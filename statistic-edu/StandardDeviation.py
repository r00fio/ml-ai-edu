# Итог
# Mean = 10.75
# Standard deviation ≈ 1.48
# Что это означает интуитивно
#
# Среднее значение данных — около 10.75.
#
# А standard deviation ≈ 1.48 говорит:
#
# типичное отклонение чисел от среднего — примерно полтора.
#
# То есть большинство чисел лежит примерно в диапазоне:
#
# 10.75±1.48
#
# то есть:
#
# [9.27, 12.23]
#
# И действительно — большинство наших чисел там и находится.
#
# Почему это важно в финансах
#
# Если это доходности:
#
# высокий mean → стратегия прибыльная
# высокий std → стратегия рискованная
#
# Две стратегии могут иметь одинаковый mean, но одна будет намного более “дерганой”.
#
# Именно поэтому в quantitative finance часто считают:
#
# mean return
# standard deviation
# Sharpe ratio

import numpy as np

data = [10,12,9,11,10,13,8,12,11,10,
        9,14,13,10,11,12,9,10,11,10]

mean = np.mean(data)
std = np.std(data)

print(mean)  # 10.75
print(std)   # 1.479...